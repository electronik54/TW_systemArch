-- ============================================================================
--  V1 - identity: the users table
-- ============================================================================
--  identity-service's own schema. Nothing outside this service reads it: no
--  other service joins users, and no other service stores a copy of a password
--  hash. That boundary (`plan.md` §3.1) is why `catalog.subscriptions.user_id`
--  is a bare UUID with no foreign key.
--
--  Flyway rules as everywhere else in this project: forward only, one
--  transaction, no dependency on application code. This file is the ONLY way
--  the table is created - Hibernate runs with `ddl-auto: validate` and is
--  allowed to complain, never to create.
-- ============================================================================

CREATE TABLE users (
    -- Generated by the application, so the id is known before the INSERT and can
    -- travel in an event (Day 11). Same decision as `events.id`.
    id              uuid         PRIMARY KEY,

    -- The login name. Sized at 320 because RFC 5321 caps an address there; the
    -- practical limit is 254, and a column that cannot hold the theoretical
    -- maximum is a column that silently rejects a valid address one day.
    email           varchar(320) NOT NULL,

    -- THE HASH, NEVER THE PASSWORD. 100 characters cushions the algorithm
    -- migration: BCrypt produces 60, Argon2id produces about 97. Sizing this
    -- column for BCrypt alone would force a schema change on the day we upgrade
    -- the algorithm - and that day always comes.
    password_hash   varchar(100) NOT NULL,

    -- Account state, kept SEPARATE from "knows the password" (plan.md 4.1).
    -- A locked user with a correct password is still refused, and the reason is
    -- visible in the data instead of hidden in a boolean.
    status          varchar(16)  NOT NULL DEFAULT 'ENABLED',

    -- The user's role in the product. One column, not a join table: EXR gives a
    -- user exactly one role, and a join table would buy flexibility nobody asked
    -- for and an extra query on every login.
    role            varchar(16)  NOT NULL DEFAULT 'FREE_USER',

    created_at      timestamptz  NOT NULL DEFAULT now(),
    updated_at      timestamptz  NOT NULL DEFAULT now(),

    -- Optimistic locking, like every mutable table here: two admin actions on
    -- one account must not silently overwrite each other.
    version         bigint       NOT NULL DEFAULT 0,

    CONSTRAINT users_status_chk CHECK (status IN ('ENABLED', 'LOCKED', 'SUSPENDED')),
    CONSTRAINT users_role_chk   CHECK (role IN ('FREE_USER', 'PAID_USER', 'ADMIN', 'DEVELOPER'))
);

-- ---------------------------------------------------------------------------
--  Uniqueness is on the LOWER-CASED email, not on the email
-- ---------------------------------------------------------------------------
--  `Alice@Example.com` and `alice@example.com` are the same mailbox, but a plain
--  UNIQUE(email) treats them as two rows - which is how one person ends up with
--  two accounts, two subscriptions and no way to log in to the one they meant.
--
--  Why an index and not a column: `citext` (a case-insensitive text type) would
--  need an extension enabled on every database, including ones a managed service
--  gives us. A functional UNIQUE INDEX needs nothing, and it is the same object
--  that answers the login lookup.
--
--  The consequence to remember when writing the repository: the query must also
--  use lower(email), or the index is not usable and every login scans the table.
CREATE UNIQUE INDEX users_email_uk ON users (lower(email));

COMMENT ON TABLE users IS
    'Login identities. Owned by identity-service; no other service reads it. '
    'Passwords are BCrypt hashes - the plaintext is never stored anywhere.';
