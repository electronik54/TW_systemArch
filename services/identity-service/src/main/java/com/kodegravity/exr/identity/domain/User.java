package com.kodegravity.exr.identity.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Table;
import jakarta.persistence.Version;

import java.time.Duration;
import java.time.Instant;
import java.util.Objects;
import java.util.UUID;

/**
 * One row of {@code users} — someone who can log in.
 *
 * <p><b>The field that matters most is the one that is absent:</b> there is no
 * {@code password} here, and there never will be. What the row holds is
 * {@link #passwordHash}, a one-way BCrypt digest. Nothing in this service can
 * recover the original string, so a stolen dump costs the attacker a slow guess
 * per row rather than a plaintext list they can try elsewhere.
 *
 * <p>The mapping is deliberately exact: every column of {@code V1} has a field here, and so do
 * the two lockout columns {@code V2} added, with {@code length} and {@code columnDefinition}
 * only where Hibernate's default would differ from the DDL. {@code ddl-auto: validate} compares
 * the two at startup and refuses to boot on any disagreement - which is the cheapest schema
 * test there is.
 */
@Entity
@Table(name = "users")
public class User {

    /** Generated by the application, like every id in this project. */
    @Id
    @Column(name = "id", nullable = false, updatable = false)
    private UUID id;

    /**
     * The login name, always stored as typed and compared lower-cased.
     *
     * <p>The uniqueness rule lives in the database (`users_email_uk` on
     * {@code lower(email)}), not here: application checks can be bypassed by a
     * concurrent request, a retry or a bug, while the index cannot. The
     * consequence for code: every lookup must also use {@code lower(email)} or
     * the index is skipped.
     */
    @Column(name = "email", nullable = false, length = 320)
    private String email;

    /**
     * A BCrypt digest: 60 characters today, hence the 100-character column —
     * Argon2id needs about 97, and the algorithm WILL be upgraded one day.
     *
     * <p>Never logged, never returned in an API response, never put in a
     * {@code toString}. A hash in a log file is a hash an attacker can work on
     * offline at leisure, with no rate limit.
     */
    @Column(name = "password_hash", nullable = false, length = 100)
    private String passwordHash;

    /**
     * Whether this identity may authenticate at all. Kept apart from "the
     * password is correct", because those are two different facts: a correct
     * password on a suspended account must still be refused.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 16)
    private UserStatus status = UserStatus.ENABLED;

    /** One rung of the product ladder. See {@link UserRole}. */
    @Enumerated(EnumType.STRING)
    @Column(name = "role", nullable = false, length = 16)
    private UserRole role = UserRole.FREE_USER;

    /** Stamped by us: V1 declares defaults but creates no trigger. */
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    /** Optimistic locking — two admin edits must not silently overwrite each other. */
    @Version
    @Column(name = "version", nullable = false)
    private long version;

    /**
     * Consecutive failures since the last success. Reset by a successful login.
     *
     * <p><b>Why {@code short} and not {@code int}.</b> The column is {@code smallint}, and
     * {@code ddl-auto: validate} compares the JDBC type code, not the column's name or width:
     * a Java {@code int} announces {@code INTEGER}, so startup died with <i>"found [int2
     * (Types#SMALLINT)], but expecting [integer (Types#INTEGER)]"</i>. Hibernate maps
     * {@code short} to {@code SMALLINT} with no hint needed, which is why the field is the
     * thing that moved - the migration was already applied, and editing it would have
     * exchanged this failure for a Flyway checksum mismatch. The same rule as the {@code char(2)}
     * column in the catalogue: the Java type decides what the validator expects.
     *
     * <p>{@code short} holds 32767, and this counter stops at {@link #recordFailedLogin}'s
     * threshold (5), so there is no room to overflow.
     */
    @Column(name = "failed_attempts", nullable = false)
    private short failedAttempts;

    /**
     * Login is refused until this instant; {@code null} means not locked.
     *
     * <p>A deadline rather than a flag, because a permanent lock would let any
     * stranger deny service to any account by guessing wrong passwords.
     */
    @Column(name = "locked_until")
    private Instant lockedUntil;

    /** Required by JPA, never by us. */
    protected User() {
    }

    /**
     * A new account. The hash is passed already computed, so this class never
     * sees a plaintext password and cannot accidentally keep one.
     */
    public User(UUID id, String email, String passwordHash, UserRole role) {
        this.id = id;
        this.email = email;
        this.passwordHash = passwordHash;
        this.role = role;
    }

    @PrePersist
    @PreUpdate
    void stampTimestamps() {
        Instant now = Instant.now();
        if (createdAt == null) {
            createdAt = now;
        }
        updatedAt = now;
    }

    /** True only when this account is allowed to authenticate at all. */
    public boolean isActive() {
        return status == UserStatus.ENABLED;
    }

    /**
     * The lockout clock, kept next to the counter it belongs to.
     *
     * <p>Two rules in one method: a failure counts, and the nth one sets a
     * deadline. Splitting them into two setters would let a caller increment
     * without locking, or lock without counting, and neither state means anything.
     *
     * @param maxAttempts failures allowed before the door closes
     * @param lockFor     how long it stays closed
     */
    public void recordFailedLogin(int maxAttempts, Duration lockFor) {
        // An expired lock starts a fresh run: the previous attack finished its
        // sentence, so the next failure is failure number one, not number six.
        if (lockedUntil != null && !lockedUntil.isAfter(Instant.now())) {
            failedAttempts = 0;
        }
        lockedUntil = null;
        failedAttempts++;

        if (failedAttempts >= maxAttempts) {
            lockedUntil = Instant.now().plus(lockFor);
        }
    }

    /** A successful login proves the owner is present, so the count goes back to zero. */
    public void recordSuccessfulLogin() {
        failedAttempts = 0;
        lockedUntil = null;
    }

    /** Whether the temporary lockout is in force right now. */
    public boolean isTemporarilyLocked(Instant now) {
        return lockedUntil != null && lockedUntil.isAfter(now);
    }

    public int getFailedAttempts() {
        return failedAttempts;
    }

    public Instant getLockedUntil() {
        return lockedUntil;
    }

    public UUID getId() {
        return id;
    }

    public String getEmail() {
        return email;
    }

    public String getPasswordHash() {
        return passwordHash;
    }

    public UserStatus getStatus() {
        return status;
    }

    public void setStatus(UserStatus status) {
        this.status = status;
    }

    public UserRole getRole() {
        return role;
    }

    public void setRole(UserRole role) {
        this.role = role;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public long getVersion() {
        return version;
    }

    @Override
    public boolean equals(Object other) {
        if (this == other) {
            return true;
        }
        if (!(other instanceof User user)) {
            return false;
        }
        return id != null && id.equals(user.id);
    }

    @Override
    public int hashCode() {
        return Objects.hashCode(id);
    }

    /** No hash, no email: this string ends up in logs. */
    @Override
    public String toString() {
        return "User[" + id + " " + status + " " + role + "]";
    }
}
