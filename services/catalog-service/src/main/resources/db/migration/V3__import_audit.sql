-- ============================================================================
--  V3 - import_attempts: the record that must SURVIVE a failed import
-- ============================================================================
--  Day 2.7, step 2 (transaction propagation).
--
--  The problem this table exists for: an import that fails has to leave a
--  trace, or nobody ever learns that a supplier stopped responding. The trace
--  cannot live in the same transaction as the import, because that transaction
--  is about to be rolled back - the trace would roll back with it and vanish
--  exactly when it is needed.
--
--  So the writing of this row uses a SECOND, independent transaction
--  (`REQUIRES_NEW`), and this table is where that second transaction commits.
--
--  WHY NOT put the attempt on `events` or `sources`
--  Both describe things that exist. An attempt is a fact about something that
--  FAILED to exist, so it has no event to hang off and no row to update.
--
--  WHY THERE IS NO INDEX BEYOND THE PRIMARY KEY
--  Today every read of this table is "show me recent failures", which the
--  primary key plus a date filter cannot answer well - but the table is written
--  once per failed import, i.e. a handful of rows a day. An index would be a
--  cost with no measurable benefit until the volume justifies it, and adding
--  one later is one line in a new migration. Guessing at an index now is how
--  write-heavy tables end up slower than the query they were built for.
-- ============================================================================

CREATE TABLE import_attempts (
    -- Generated by the application, like `events.id`, so the id is known before
    -- the row is written and can be logged even if the insert later fails.
    id              uuid         PRIMARY KEY,

    -- WHICH supplier's import failed. The one thing every failure needs to be
    -- actionable: "TMDB has been failing since Tuesday".
    source_id       smallint     NOT NULL REFERENCES sources (id),

    -- How many items the batch was carrying. A failed import of 1 item is a
    -- data problem; a failed import of 40 000 is an outage. Same table, and the
    -- number is what tells them apart without reading a log file.
    event_count     integer      NOT NULL CHECK (event_count >= 0),

    -- When the attempt began. `timestamptz`, always: this is a moment in time,
    -- not a calendar day (contrast `events.release_date`, which is a DATE on
    -- purpose).
    started_at      timestamptz  NOT NULL DEFAULT now(),

    -- NULL while the attempt is running. Not strictly needed for the demo,
    -- but it is what makes this a log of attempts rather than of failures, and
    -- the difference decides whether a crashed process leaves a visible row.
    failed_at       timestamptz,

    -- The driver's message, truncated by the application before writing: a
    -- Postgres error can carry the failing row's values, and a log table is not
    -- the place to discover a leaked synopsis.
    error           text
);

COMMENT ON TABLE import_attempts IS
    'One row per import attempt. Written in its OWN transaction (REQUIRES_NEW) '
    'so the record of a failure survives the rollback of the import itself.';
