    (2, 'IGDB',   'IGDB (Twitch)',      180,  3600,  'ANONYMISE'),
    (3, 'SEED',   'EXR seed data',      3650, 86400, 'KEEP_TITLE'),
    (4, 'MANUAL', 'Entered by an admin', 3650, 86400, 'KEEP_TITLE');


-- ---------------------------------------------------------------------------
-- events — the things with dates
--
-- The table is deliberately split into two halves (catalog/schema.md §2):
--   * THE SKELETON (id, source, external_id, title, release_date, status,
--     availability, active_until) — survives expiry, because it is what keeps
--     autocomplete, history and subscriptions alive.
--   * THE DETAILS (synopsis, poster, genres, ...) — purged when the licence
--     clock runs out, and re-fetched on demand.
-- ---------------------------------------------------------------------------
CREATE TABLE events (
    id                    uuid         PRIMARY KEY DEFAULT gen_random_uuid(),

    -- which supplier this came from, and the supplier's own product number.
    -- Together they are UNIQUE, which is what makes ingestion idempotent: the
    -- same item imported twice updates one row instead of creating two.
    source_id             smallint     NOT NULL REFERENCES sources (id),
    external_id           varchar(64)  NOT NULL,

    -- hierarchy: an episode's parent is a season; a season's parent is a series;
    -- one concert date's parent is the tour. NULL = top level.
    -- A SEQUEL IS NOT A CHILD - that is a separate event.
    parent_event_id       uuid         REFERENCES events (id) ON DELETE CASCADE,

    category              varchar(16)  NOT NULL,
    title                 varchar(300) NOT NULL,

    -- a release DATE is a calendar day, identical in every timezone.
    -- NULL means "not announced yet". `release_precision` records how exact we
    -- are, so "March 2025" never has to be faked into 2025-03-01.
    release_date          date,
    release_precision     varchar(10)  NOT NULL DEFAULT 'UNKNOWN',

    -- what we know about the release itself
    status                varchar(16)  NOT NULL DEFAULT 'ANNOUNCED',

    -- whether the DETAILS are present, and whether the event is still worth
    -- refreshing or subscribing to. Two different questions, two columns.
    availability          varchar(16)  NOT NULL DEFAULT 'FRESH',
    active_until          timestamptz,
    details_expired_at    timestamptz,

    -- ---------------------------- details (expire) -------------------------
    synopsis              text,
    poster_url            text,
    external_url          text,
    genres                text[]       NOT NULL DEFAULT '{}',
    platforms             text[]       NOT NULL DEFAULT '{}',
    network               varchar(120),
    venue                 varchar(200),
    city                  varchar(120),
    country               char(2),
    source_updated_at     timestamptz,
    last_synced_at        timestamptz,

    -- freshness machinery (catalog/schema.md §11):
    --   details_hash   - fingerprint of the detail fields; a poll that produces
    --                    the same hash is NOT a change, so nobody gets notified
    --   last_change_at - drives the HOT/WARM/COLD promotion and decay
    details_hash          char(64),
    last_change_at        timestamptz,

    -- ------------------- editorial overrides (NEVER purged) ----------------
    -- Our own record, not the supplier's: an admin authored these, so the
    -- retention clock has no claim on them. Effective value =
    -- COALESCE(override, sourced).
    title_override        varchar(300),
    release_date_override date,
    overridden_fields     text[]       NOT NULL DEFAULT '{}',
    override_author_id    uuid,
    override_updated_at   timestamptz,

    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now(),
    version               bigint       NOT NULL DEFAULT 0,

    -- ------------------------------------------------------- constraints ---
    CONSTRAINT events_source_external_uk UNIQUE (source_id, external_id),

    CONSTRAINT events_category_chk CHECK (category IN
        ('GAME', 'MOVIE', 'TV_SERIES', 'ANIME', 'LOCAL_EVENT')),

    CONSTRAINT events_status_chk CHECK (status IN
        ('ANNOUNCED', 'CONFIRMED', 'DELAYED', 'RELEASED', 'CANCELLED')),

    CONSTRAINT events_availability_chk CHECK (availability IN
        ('FRESH', 'STALE', 'GONE')),

    CONSTRAINT events_precision_chk CHECK (release_precision IN
        ('DAY', 'MONTH', 'YEAR', 'UNKNOWN')),

    -- precision and date must tell the same story: you cannot claim "unknown"
    -- while storing a date, nor claim a day without one. Applies to the SOURCED
    -- pair only - an admin override may legitimately fill a gap.
    CONSTRAINT events_precision_date_chk CHECK (
        (release_precision =  'UNKNOWN' AND release_date IS NULL) OR
        (release_precision <> 'UNKNOWN' AND release_date IS NOT NULL)
    ),

    CONSTRAINT events_no_self_parent_chk CHECK (
        parent_event_id IS NULL OR parent_event_id <> id
    )
);


-- ---------------------------------------------------------------------------
-- subscriptions — who wants to be told about what
-- ---------------------------------------------------------------------------
CREATE TABLE subscriptions (
    id                 uuid        PRIMARY KEY DEFAULT gen_random_uuid(),

    -- NO FOREIGN KEY. Users live in identity-service's database, so a foreign key
    -- here would require a shared database - the distributed-monolith anti-pattern
    -- we designed against (plan.md §3.1). The cost: nothing stops a subscription
    -- pointing at a deleted user. That is handled by the UserDeleted event
    -- (Day 13.6), not by a constraint.
    user_id            uuid        NOT NULL,

    -- This one IS a real foreign key: events belong to this service.
    event_id           uuid        NOT NULL REFERENCES events (id) ON DELETE CASCADE,

    -- how far the subscription reaches into a hierarchy (catalog/schema.md §12)
    --   THIS_EVENT        just this one (one concert date, one episode)
    --   THIS_AND_FUTURE   this one and every later sibling ("from episode 5 on")
    --   INCLUDE_CHILDREN  the whole container (the series, the season, the tour)
    subscription_scope varchar(24) NOT NULL DEFAULT 'THIS_EVENT',

    notify_on_new      boolean     NOT NULL DEFAULT true,
    notify_on_update   boolean     NOT NULL DEFAULT true,

    -- 1440 = 1 day, 10080 = 7 days, max 30 days. Minutes, so there is no unit
    -- ambiguity and no enum to extend.
    lead_time_minutes  integer     NOT NULL DEFAULT 1440,

    channels           text[]      NOT NULL DEFAULT '{EMAIL}',

    -- When the subscription stopped being "live", and why. ONE timestamp covers
    -- every reason, so "is this active?" stays a single predicate:
    --   USER            the user unsubscribed
    --   EVENT_ENDED     the event was archived (finished/cancelled)
    --   TIER_DOWNGRADE  the user dropped to a tier with fewer slots
    ended_at           timestamptz,
    end_reason         varchar(16),

    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    version            bigint      NOT NULL DEFAULT 0,

    CONSTRAINT subscriptions_lead_time_chk CHECK (lead_time_minutes BETWEEN 0 AND 43200),
    CONSTRAINT subscriptions_scope_chk CHECK (subscription_scope IN
        ('THIS_EVENT', 'THIS_AND_FUTURE', 'INCLUDE_CHILDREN')),
    CONSTRAINT subscriptions_end_reason_chk CHECK (end_reason IS NULL OR end_reason IN
        ('USER', 'EVENT_ENDED', 'TIER_DOWNGRADE')),
    -- a reason without a timestamp (or the reverse) is a bug, not a state
    CONSTRAINT subscriptions_ended_pair_chk CHECK (
        (ended_at IS NULL AND end_reason IS NULL) OR
        (ended_at IS NOT NULL AND end_reason IS NOT NULL)
    )
);


-- ---------------------------------------------------------------------------
-- event_reports — crowd-sourced "please check this" flags (catalog/schema.md §14)
--
-- This does NOT trigger a refetch. It creates a work item for an admin and
-- carries the comment saying WHAT looks wrong - which a refetch never could.
-- ---------------------------------------------------------------------------
CREATE TABLE event_reports (
    id           uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
    event_id     uuid          NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    reporter_id  uuid          NOT NULL,          -- no FK: users live in identity
    comment      varchar(1000),
    status       varchar(16)   NOT NULL DEFAULT 'OPEN',
    resolved_by  uuid,
    resolved_at  timestamptz,
    created_at   timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT event_reports_status_chk CHECK (status IN ('OPEN', 'RESOLVED', 'DISMISSED')),
    CONSTRAINT event_reports_resolved_pair_chk CHECK (
        (status = 'OPEN' AND resolved_at IS NULL) OR
        (status <> 'OPEN' AND resolved_at IS NOT NULL)
    )
);


-- ===========================================================================
--  INDEXES
--
--  Every index is a trade: reads get faster, writes get slower, disk grows.
--  So each one below exists for a NAMED query. A PARTIAL index only covers rows
--  matching its WHERE clause - smaller, cheaper to maintain, and often the
--  difference between an instant count and a full table scan.
-- ===========================================================================

-- ------------------------------------------------------------------ events --
-- the main screen: upcoming releases in date order, cancelled ones excluded
CREATE INDEX events_release_date_idx
    ON events (release_date)
    WHERE status <> 'CANCELLED';

-- filtering by genre / platform. GIN is the "quick-find list" for multi-valued
-- columns such as arrays.
CREATE INDEX events_genres_gin    ON events USING gin (genres);
CREATE INDEX events_platforms_gin ON events USING gin (platforms);

-- local events filtered by city
CREATE INDEX events_city_idx
    ON events (city)
    WHERE city IS NOT NULL;

-- the nightly PURGE job's query: "this source, last synced before the cutoff"
CREATE INDEX events_purge_idx
    ON events (source_id, last_synced_at)
    WHERE availability = 'FRESH';

-- the REFRESH scheduler: "what is active and going stale?"
CREATE INDEX events_refresh_idx
    ON events (active_until, last_synced_at)
    WHERE active_until IS NOT NULL;

-- navigating the hierarchy (series → seasons → episodes)
CREATE INDEX events_parent_idx
    ON events (parent_event_id)
    WHERE parent_event_id IS NOT NULL;

-- ----------------------------------------------------------- subscriptions --
-- ⭐ THE MOST IMPORTANT LINE IN THIS FILE ⭐
-- At most ONE LIVE subscription per (user, event). It is partial, so rows that
-- have ended are outside the rule - which is why unsubscribing and resubscribing
-- still works. This single constraint kills the double-tap problem, and it is
-- the foundation of the atomic 2-event quota check on Day 8.
CREATE UNIQUE INDEX subscriptions_active_uk
    ON subscriptions (user_id, event_id)
    WHERE ended_at IS NULL;

-- "my subscriptions", and the free-tier slot count
CREATE INDEX subscriptions_user_active_idx
    ON subscriptions (user_id)
    WHERE ended_at IS NULL;

-- fan-out: "who wants to know about this event?"
CREATE INDEX subscriptions_event_idx
    ON subscriptions (event_id)
    WHERE ended_at IS NULL;

-- ------------------------------------------------------------ event_reports --
-- one OPEN report per person per event - the anti-spam rule, same shape as above
CREATE UNIQUE INDEX event_reports_open_uk
    ON event_reports (event_id, reporter_id)
    WHERE status = 'OPEN';

-- the admin queue: open reports, oldest first
CREATE INDEX event_reports_queue_idx
    ON event_reports (status, created_at);

-- "how many people flagged this event?" - ranks the queue by signal strength
CREATE INDEX event_reports_event_idx
    ON event_reports (event_id);



