-- ============================================================================
--  V1 — catalog schema
--  ---------------------------------------------------------------------------
--  Owned entirely by catalog-service. Nothing outside this service reads or
--  writes these tables. There is deliberately NO users table here: users live
--  in identity-service, so we store a bare `user_id` with no foreign key.
--
--  Flyway rules this file obeys (see plan.md Day 2.3):
--    1. FORWARD ONLY. A migration that has run anywhere is never edited. To
--       change something later you write V2, V3, ... — never touch V1.
--    2. It is applied exactly once, inside its own transaction, and recorded
--       in the `flyway_schema_history` table.
--    3. It must not depend on application code. Plain SQL only.
--    4. It is safe to run against an EMPTY database, and it is the only way
--       that schema is ever created — no `ddl-auto` in Hibernate ever touches it.
--
--  Conventions:
--    * ids are uuid, generated by the application (and defaulted here so manual
--      SQL and seeds also work). The app needs the id BEFORE insert so it can
--      publish an outbox event in the same transaction (Day 11).
--    * timestamps are timestamptz — always store an instant, never a wall clock.
--    * enumerated values are varchar + CHECK, never a native pg enum, so adding
--      a value later is a one-line change rather than an ALTER TYPE.
--    * every mutable table carries `version` for optimistic locking.
-- ============================================================================


-- ---------------------------------------------------------------------------
-- sources — where the information comes from (a tiny, fixed list)
-- ---------------------------------------------------------------------------
CREATE TABLE sources (
    id                     smallint     PRIMARY KEY,

    -- short machine name used in code and logs
    code                   varchar(20)  NOT NULL,
    display_name           varchar(100) NOT NULL,

    -- HOW LONG WE MAY KEEP THE RICH DETAILS. This is a LICENCE rule, not a
    -- preference, which is why it lives in a table an admin can change rather
    -- than in application.yml where changing it needs a deploy.
    details_retention_days integer      NOT NULL,
    cache_ttl_seconds      integer      NOT NULL,

    -- WHAT HAPPENS WHEN THE CLOCK RUNS OUT (see catalog/schema.md §8)
    --   KEEP_TITLE : purge nothing, just stop refreshing
    --   ANONYMISE  : null the details, replace the title with a placeholder
    --   DELETE_ALL : remove the row entirely (subscriptions cascade)
    expiry_policy          varchar(20)  NOT NULL DEFAULT 'ANONYMISE',

    enabled                boolean      NOT NULL DEFAULT true,
    created_at             timestamptz  NOT NULL DEFAULT now(),
    updated_at             timestamptz  NOT NULL DEFAULT now(),

    CONSTRAINT sources_code_uk UNIQUE (code),
    CONSTRAINT sources_retention_chk CHECK (details_retention_days > 0),
    CONSTRAINT sources_ttl_chk       CHECK (cache_ttl_seconds > 0),
    CONSTRAINT sources_policy_chk    CHECK (expiry_policy IN ('KEEP_TITLE', 'ANONYMISE', 'DELETE_ALL'))
);

-- Reference data. Explicit ids because they are part of the contract: the code
-- refers to them, and renumbering later would silently re-point existing rows.
