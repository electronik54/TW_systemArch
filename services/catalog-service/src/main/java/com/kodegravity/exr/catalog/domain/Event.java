package com.kodegravity.exr.catalog.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.time.LocalDate;
import java.util.UUID;

/**
 * One row of {@code events}. Deliberately incomplete for now: only the columns
 * that carry a NEW mapping idea are here. Unmapped columns are fine — Hibernate
 * validates what is mapped and ignores the rest.
 */
@Entity
@Table(name = "events")
public class Event {

    /**
     * A {@link UUID}, generated by the application (not by the database), so the
     * id is already known when the row is written — that is what lets an outbox
     * event carry it in the same transaction (Day 11).
     */
    @Id
    @Column(name = "id", nullable = false, updatable = false)
    private UUID id;

    /**
     * The foreign key {@code source_id}, mapped as an OBJECT instead of as a
     * {@code Short}.
     *
     * <p>{@code @ManyToOne} reads as "many events, one source". {@code @JoinColumn}
     * names the column that holds the link. The point of typing the field
     * {@code Source} rather than {@code short} is that the code never has to look
     * the supplier up by hand: {@code event.getSource().getDisplayName()}.
     *
     * <p>{@code fetch = LAZY} overrides JPA's default, which for {@code @ManyToOne}
     * is <b>EAGER</b> — the single biggest source of accidental extra queries.
     * A lazy field returns a stand-in proxy that loads on first use, so touching
     * it outside a transaction throws. We'll fetch it in ONE query with
     * {@code @EntityGraph} later in this day.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "source_id", nullable = false, updatable = false)
    private Source source;

    /** The supplier's own id for this item. Unique together with {@link #source}. */
    @Column(name = "external_id", nullable = false, length = 64, updatable = false)
    private String externalId;

    /**
     * NOT NULL in Postgres and with NO database default, so the INSERT must carry
     * it. Hibernate writes only the columns that are mapped here — everything
     * unmapped is left to the database, which fills in a DEFAULT if one exists
     * and otherwise refuses the row. (Becomes an enum later; a String for now.)
     */
    @Column(name = "category", nullable = false, length = 16)
    private String category;

    @Column(name = "title", nullable = false, length = 300)
    private String title;

    /**
     * A release DATE is a calendar day, identical in every timezone, so it is a
     * {@link LocalDate} — not an {@code Instant}. Getting this wrong is how
     * "releases on the 5th" turns into "releases on the 4th" for half the world.
     */
    @Column(name = "release_date")
    private LocalDate releaseDate;

    /**
     * Paired with {@link #releaseDate} by a CHECK constraint: there is no way to
     * store "March 2025" as a fake 2025-03-01 — the date plus this tag say how
     * exact the knowledge is. Two ordinary columns that only make sense together.
     */
    @Column(name = "release_precision", nullable = false, length = 10)
    private String releasePrecision;

    /**
     * The container this event belongs to, if any: an episode's parent is a
     * season, a season's parent is a series, one concert date's parent is the
     * tour. {@code null} means "top level".
     *
     * <p>Nothing new here — it is the same {@code @ManyToOne} as {@link #source},
     * except the other row lives in <b>this same table</b>. That is all a
     * "self-reference" is.
     *
     * <p>No {@code optional = false}: the column is nullable, and most events are
     * top level. The DDL's {@code ON DELETE CASCADE} means deleting a series
     * removes its episodes too.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "parent_event_id")
    private Event parent;

    protected Event() {
    }

    public Event(UUID id, Source source, String externalId, String category,
                 String title, LocalDate releaseDate, String releasePrecision) {
        this.id = id;
        this.source = source;
        this.externalId = externalId;
        this.category = category;
        this.title = title;
        this.releaseDate = releaseDate;
        this.releasePrecision = releasePrecision;
    }

    public UUID getId() {
        return id;
    }

    public Source getSource() {
        return source;
    }

    public String getExternalId() {
        return externalId;
    }

    public String getCategory() {
        return category;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public LocalDate getReleaseDate() {
        return releaseDate;
    }

    public void setReleaseDate(LocalDate releaseDate) {
        this.releaseDate = releaseDate;
    }
}
